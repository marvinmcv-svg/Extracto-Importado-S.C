/** Score: higher when the accord appears earlier (dominant). */
export function groupScore(item, groupId) {
  const g = accordGroups.find((x) => x.id === groupId);
  return item.accords.reduce((s, a, i) => s + (g.match.includes(a) ? (6 - Math.min(i, 5)) : 0), 0);
}

